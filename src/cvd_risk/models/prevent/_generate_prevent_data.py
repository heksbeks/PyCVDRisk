'''
This script is generating prevent_data.py from sysdata.rda
'''

import importlib.util, math, subprocess, sys
from pathlib import Path

script_dir = Path(__file__).parent.resolve()

packages = ['pandas', 'numpy', 'rpy2']
missing = [pkg for pkg in packages if importlib.util.find_spec(pkg.replace('-', '_')) is None]
if missing:
	print(f'Installing missing packages {missing}...')
	subprocess.check_call([sys.executable, '-m', 'pip', 'install'] + missing)
	print('Finished installing packages!\n')

import rpy2.robjects as robjects
from rpy2.robjects import pandas2ri
from rpy2.robjects.conversion import localconverter

# get sysdata.rda from https://github.com/martingmayer/preventr
# https://github.com/martingmayer/preventr/blob/main/R/sysdata.rda
robjects.r['load'](r"C:\INSTALL\tracker\preventr\R\sysdata.rda")

r_objects = list(robjects.r['ls']())
print()
print("Objects inside RDA:", r_objects)
print()
s = []
s.append('# do not edit, this file is generated by _generate_prevent_data.py')
s.append('')
s.append('COEFFS = {')
SDI_GROUP = bytearray(100000)


coeff_names = [
	'Constant',
	'Age per 10 years',
	'Age per 10 years squared',
	'non-HDL-C per 1 mmol/L',
	'HDL-C per 0.3 mmol/L',
	'SBP <110 per 20 mmHg',
	'SBP ≥110 per 20 mmHg',
	'Diabetes',
	'Current smoking',
	'BMI <30, per 5 kg/m2',
	'BMI 30+, per 5 kg/m2',
	'eGFR <60, per -15 ml',
	'eGFR 60+, per -15 ml',
	'Anti-hypertensive use',
	'Statin use',
	'Treated SBP ≥110 mm Hg per 20 mm Hg',
	'Treated non-HDL-C',
	'Age per 10yr * non-HDL-C per 1 mmol/L',
	'Age per 10yr * HDL-C per 0.3 mmol/L',
	'Age per 10yr * SBP ≥110 mm Hg per 20 mmHg',
	'Age per 10yr * diabetes',
	'Age per 10yr * current smoking',
	'Age per 10yr * BMI 30+ per 5 kg/m2',
	'Age per 10yr * eGFR <60, per -15 ml',
	'SDI decile categories 4-6 vs. 1-3',
	'SDI decile categories 7-10 vs. 1-3',
	'Missing SDI',
	'ln-UACR, mg/g, per 1 ln unit',
	'Missing UACR/PCR/Dipstick',
	'HbA1c no DM, per 1%',
	'HbA1c in DM, per 1%',
	'Missing HbA1c'
]


with localconverter(robjects.default_converter + pandas2ri.converter):

	print('extracting coeffs...')
	s.append('    # ' + str(coeff_names))

	for o in r_objects:
		if not o.endswith('yr'):
			continue
		s.append('#'*99)
		r_data = robjects.r[o]
		df = robjects.conversion.rpy2py(r_data)
		rnames = list(df['beta_coefficients'])
		o1, o2 = o[:-2].split('_')
		for col in df.columns.tolist():
			if col == 'beta_coefficients':
				continue
			col2 = col.replace('heart_failure', 'hf')
			nn = f"{o1}_{col2}_{o2}"
			s.append(f"    '{nn}' :")
			d = [0.]*len(coeff_names)
			for n, v in zip(rnames, list(df[col])):
				if n not in coeff_names:
					raise RuntimeError(f'unknown name "{n}", you might have to update coeff_names')
				d[coeff_names.index(n)] = v
			s.append(f'        {d},')

	print('extracting sdi_decile_dat...')
	r_data = robjects.r['sdi_decile_dat']
	df = robjects.conversion.rpy2py(r_data)
	for z, v in zip(df['zip'], df['sdi_decile']):
		if not math.isfinite(v) or not v:
			continue
		zip_code = int(z)
		SDI = int(v)
		if 90800 <= zip_code <= 90890:
			print(zip_code, SDI)
		if 0 < SDI < 4:
			SDI_GROUP[zip_code] = 1
		elif 4 <= SDI < 7:
			SDI_GROUP[zip_code] = 2
		elif 7 <= SDI <= 10:
			SDI_GROUP[zip_code] = 3
		else:
			print(z, v)
			raise RuntimeError(f'out of range sdi {SDI}')


s.append('}')
s.append('')


m = ','.join([str(sdi) for sdi in SDI_GROUP])
s.append(f'SDI_GROUP = [{m}]')
s.append('')

p = script_dir / 'prevent_data_NEW.py'
print('writing output file', p)
with open(p, 'w', encoding='utf8') as f:
	f.write('\n'.join(s))

print()
print('finished')
print()
